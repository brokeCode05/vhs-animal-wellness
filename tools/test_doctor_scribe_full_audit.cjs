'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const sandbox = { window:{VHS_DOCTOR_SCRIBE_GEMINI:false}, Date, Promise, setTimeout, clearTimeout };
sandbox.window.setTimeout=setTimeout; sandbox.window.clearTimeout=clearTimeout;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root,'public/doctor/doctor-scribe.js'),'utf8'), sandbox);
const s = sandbox.window.DoctorScribe;
let count=0;
function eq(a,b,info){assert.equal(a,b,info);count++;}
function okay(a,info){assert.ok(a,info);count++;}
function draft(input){let r=s.generateSoapDraft(input);okay(r.ok,`Should generate: ${input}`);eq(r.meta.engine,'local-deterministic','No live Gemini');return r;}
const one=draft('subject owner reports that the dog has been scratching its ears for 3 days');
eq(one.soap.subjective,'owner reports that the dog has been scratching its ears for 3 days','Screenshot S');
eq(one.soap.objective.findings,s.NOT_PROVIDED,'Screenshot O empty');
eq(one.soap.assessment,s.NOT_PROVIDED,'No invented assessment');
eq(one.soap.plan,s.NOT_PROVIDED,'No invented plan');
const all=draft('Owner reports scratching both ears. On exam redness observed in both ears. I suspect ear irritation. I recommend follow up.');
okay(all.soap.subjective.includes('Owner reports scratching'),'History S');
okay(all.soap.objective.findings.includes('redness'),'Exam O');
okay(all.soap.assessment.includes('suspect'),'Doctor impression A');
okay(all.soap.plan.includes('recommend'),'Recommendation P');
const multi=draft('The dog has been scratching its ears and I see redness on examination and I suspect irritation and recommend follow up.');
okay(multi.soap.subjective.includes('scratching'),'One-line S');
okay(multi.soap.objective.findings.includes('redness'),'One-line O');
okay(multi.soap.assessment.includes('suspect'),'One-line A');
okay(multi.soap.plan.includes('recommend'),'One-line P');
const labeled=draft('Subjective: Vomiting at home. Objective: On exam ears red. Assessment: Suspected irritation. Plan: Follow up.');
okay(labeled.soap.subjective.includes('Vomiting'),'Section heading S');
okay(labeled.soap.objective.findings.includes('red'),'Section heading O');
okay(labeled.soap.assessment.includes('Suspected'),'Section heading A');
okay(labeled.soap.plan.includes('Follow up'),'Section heading P');
const taglish=draft('Medyo nagsusuka at walang gana kumain sabi ng owner. Sa examination may pamumula. Posibleng irritation. Pinayuhan na bumalik bukas.');
okay(taglish.soap.subjective.includes('nagsusuka'),'Taglish subjective');
okay(taglish.soap.objective.findings.includes('examination'),'Taglish exam');
okay(taglish.soap.assessment.includes('Posibleng'),'Taglish assessment');
okay(taglish.soap.plan.includes('Pinayuhan'),'Taglish plan');
const f=draft('Temperature 102.2 F. Weight 8.5 kg. Heart rate 120 bpm.');
eq(f.soap.objective.temperatureC,null,'Fahrenheit must not become Celsius');
okay(f.soap.objective.findings.includes('102.2 F'),'Fahrenheit source visible');
okay(f.warnings.some(x=>x.includes('Fahrenheit')),'Fahrenheit review warning');
eq(f.soap.objective.weightKg,8.5,'Weight extracted');
eq(f.soap.objective.heartRateBpm,120,'HR extracted');
const source=draft('Owner says weighed 7 kg 2 months ago. On exam 8 kg today.');
eq(source.soap.objective.weightKg,null,'Historical owner weight not current weight');
okay(source.soap.subjective.includes('7 kg'),'Historical weight retained in S');
const home=draft('Owner reports temperature 39 C taken at home.');
eq(home.soap.objective.temperatureC,null,'Owner home temp not clinician measured');
okay(home.soap.subjective.includes('temperature 39 C'),'Owner history retained');
const dup=draft('Temperature 38.5 C. Temperature 39.1 C.');
eq(dup.soap.objective.temperatureC,null,'Conflicting C measurements blank');
okay(dup.warnings.some(x=>x.includes('Conflicting temperature')),'Conflicting temperature warning');
const dupSame=draft('Temperature 38.5 C. Temperature 38.5 C.');
eq(dupSame.soap.objective.temperatureC,38.5,'Same repeated vital is okay');
const nested=draft('Weight 4.5 kg and temperature is 38.2 C. HR: 124 bpm.');
eq(nested.soap.objective.weightKg,4.5,'Current weight');
eq(nested.soap.objective.temperatureC,38.2,'Current temp');
eq(nested.soap.objective.heartRateBpm,124,'Current HR');
const plan=draft('Recommend ear examination.');
okay(plan.soap.plan.includes('Recommend'),'Recommendation plan not unclassified');
eq(plan.soap.objective.findings,s.NOT_PROVIDED,'Proposed exam not observed fact');
const ambiguous=draft('The dog has red ears.');
eq(ambiguous.soap.objective.findings,s.NOT_PROVIDED,'Unattributed anatomy not exam');
okay(ambiguous.unclassified.length===1,'Ambiguous material preserved for review');
const invented=draft('Owner reports vomiting.');
eq(invented.soap.assessment,s.NOT_PROVIDED,'Do not infer diagnosis');
eq(invented.soap.plan,s.NOT_PROVIDED,'Do not invent treatment');
eq(invented.soap.objective.heartRateBpm,null,'Do not invent vital');
const bad=s.generateSoapDraft('');eq(bad.ok,false,'Empty transcript blocked');
const long=s.generateSoapDraft('a'.repeat(8001));eq(long.ok,false,'Long transcript blocked');
const summary=s.buildPreConsultationSummary({petName:'Test Pet',serviceLabel:'Consultation',reason:'Reduced appetite',notes:''});
okay(summary.includes('Reduced appetite'),'Preconsultation reflects this appointment only');
okay(!summary.includes('vomiting'),'Preconsultation invents no additional symptoms');
const bare=s.buildPreConsultationSummary({petName:'Test Pet',serviceLabel:'Grooming'});
okay(bare.includes('No additional symptoms'),'No symptoms invented for missing reason');
const html=fs.readFileSync(path.join(root,'public/doctor/index.html'),'utf8');
const ui=fs.readFileSync(path.join(root,'public/doctor/doctor.js'),'utf8');
okay(/VHS_DOCTOR_SCRIBE_GEMINI\s*=\s*(?:true|false)/.test(html),'Clinical Gemini browser switch is explicit');
okay(html.includes('saved to the clinic server') && html.includes('clinic must approve the retention period') && html.includes('Older drafts may remain in this browser'),'Storage and retention disclosure');
okay(html.includes('external speech service'),'Dictation privacy warning');
okay(ui.includes('scribe.transcript.value !== pending.transcript'),'Review protects transcript freshness');
okay(ui.includes('Transcript changed. Generate a fresh SOAP proposal'),'Transcript edits invalidate previews');
okay(ui.includes('scribe.pendingDraft !== pending'),'Apply protects async confirmation race');
okay(ui.includes('result.unclassified && result.unclassified.length'),'Skipped sections visible during review');
okay(ui.includes('result.warnings && result.warnings.length'),'Warnings visible during review');
console.log(`PASS: comprehensive Scribe local SOAP, vitals, provenance, multilingual, review and privacy audit (${count} assertions)`);
